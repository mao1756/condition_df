def _cuda_driver_api_version() -> int | None:
    """Read the CUDA driver API version without requiring a toolkit."""

    candidates = (
        ("nvcuda.dll", getattr(ctypes, "WinDLL", ctypes.CDLL))
        if hasattr(ctypes, "WinDLL")
        else ("libcuda.so.1", ctypes.CDLL)
    )
    try:
        library = candidates[1](candidates[0])
        value = ctypes.c_int()
        status = int(library.cuDriverGetVersion(ctypes.byref(value)))
        return int(value.value) if status == 0 else None
    except (OSError, AttributeError, TypeError, ValueError):
        return None


