r"""Fused certified Gaussian/Haar copula for Jacobi level coupling.

This module is additive to the immutable Jacobi CUDA implementation.  It
reuses that implementation's header-free double-double ball arithmetic and
certified exponential, then adds a rigorously enclosed normal CDF/inverse and
the orthogonal Haar recursion.  CUDA ``normcdfinv`` is used only to propose a
small root bracket; interval Newton steps and strict endpoint tests authorize
the result.

The normal CDF is evaluated locally about quarter-integer anchors.  Anchor
values are generated by the pinned Arb backend, split into double-double
centres plus outward radii, and embedded in the NVRTC source.  On a local
coordinate ``|d| <= 1/8`` the entire exponential-integral series is summed
through degree 56.  A frozen ``2^-120`` remainder is conservative for
``|anchor| <= 38`` (the analytic majorant is below ``2^-127``).  Any lane
outside the proved domain is unresolved and must use the transition-local Arb
fallback owned by the higher-level coupling API.

The Gaussian variables produced here are a copula only.  They are never used
as a transition or state approximation.
"""

