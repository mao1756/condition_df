def calibrate_h1_trust(
    shadow_model: nn.Module,
    prestep_ema_model: nn.Module,
    batches: ReferenceTrustBatch | Sequence[ReferenceTrustBatch],
    dynamics: DirectFluxMNISTConfig,
    *,
    scaled_bce_gradient_norm: float,
    scale_floor: float = H1_TRUST_SCALE_FLOOR,
    binding: Mapping[str, Any] | None = None,
) -> H1TrustCalibration:
    """Calibrate scales and the base H1 multiplier from one shadow step.

    The caller owns the deterministic BCE shadow update and passes the norm of
    its normalized-coordinate, scaled-BCE gradient.  ``shadow_model`` is the
    post-shadow-step raw model; ``prestep_ema_model`` is the stopped EMA anchor
    from immediately before that step.  The value and energy RMS values become
    frozen scales.  ``lambda_base`` makes the normalized H1 gradient norm equal
    to the supplied scaled-BCE gradient norm at calibration.

    Every floor hit is represented explicitly and makes ``passed == 0``.  The
    clamped scales are still recorded so a failed calibration remains fully
    reportable, but its ``lambda_base`` is ``None`` and must not be trained.
    """

    floor = float(scale_floor)
    bce_norm = float(scaled_bce_gradient_norm)
    if not _finite_positive(floor):
        raise ValueError("scale_floor must be finite and positive")
    if not math.isfinite(bce_norm) or bce_norm < 0.0:
        raise ValueError("scaled_bce_gradient_norm must be finite and nonnegative")
    states, tau, labels, fingerprints, phase, task, step = _stack_batches(batches)

    raw = h1_increment_components(
        shadow_model,
        prestep_ema_model,
        tau,
        states,
        labels,
        dynamics,
        value_scale=1.0,
        energy_scale=1.0,
        create_graph=False,
    )
    value_rms = math.sqrt(max(0.0, float(raw.value_mean.detach().cpu())))
    energy_rms = math.sqrt(
        max(0.0, float(raw.natural_energy_mean.detach().cpu()))
    )
    physical_rms = math.sqrt(
        max(0.0, float(raw.physical_flux_energy_mean.detach().cpu()))
    )
    value_hit = int(not math.isfinite(value_rms) or value_rms <= floor)
    energy_hit = int(not math.isfinite(energy_rms) or energy_rms <= floor)
    bce_hit = int(not math.isfinite(bce_norm) or bce_norm <= floor)
    value_scale = max(floor, value_rms) if math.isfinite(value_rms) else floor
    energy_scale = max(floor, energy_rms) if math.isfinite(energy_rms) else floor

    normalized = h1_increment_components(
        shadow_model,
        prestep_ema_model,
        tau,
        states,
        labels,
        dynamics,
        value_scale=value_scale,
        energy_scale=energy_scale,
        create_graph=True,
    )
    h1_norm = _gradient_norm(normalized.objective, shadow_model)
    h1_hit = int(not math.isfinite(h1_norm) or h1_norm <= floor)
    passed = int(not any((value_hit, energy_hit, bce_hit, h1_hit)))
    multiplier = bce_norm / h1_norm if passed else None
    if multiplier is not None and not _finite_positive(multiplier):
        multiplier = None
        passed = 0
        h1_hit = 1

    return H1TrustCalibration(
        calibration_state_count=int(states.shape[0]),
        trust_batch_fingerprints=tuple(fingerprints),
        phase=phase,
        task=task,
        optimizer_step=step,
        value_scale=float(value_scale),
        energy_scale=float(energy_scale),
        raw_value_rms=float(value_rms),
        raw_natural_energy_rms=float(energy_rms),
        raw_physical_flux_step_rms=float(physical_rms),
        scaled_bce_gradient_norm=float(bce_norm),
        normalized_h1_gradient_norm=float(h1_norm),
        lambda_base=None if multiplier is None else float(multiplier),
        scale_floor=floor,
        value_scale_floor_hit=int(value_hit),
        energy_scale_floor_hit=int(energy_hit),
        bce_gradient_floor_hit=int(bce_hit),
        h1_gradient_floor_hit=int(h1_hit),
        passed=int(passed),
        binding={} if binding is None else dict(binding),
    )
