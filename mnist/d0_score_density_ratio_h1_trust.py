def _canonical_json(value: Any) -> bytes:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")


def _canonical_fingerprint(value: Any) -> str:
    return hashlib.sha256(_canonical_json(value)).hexdigest()


def _tensor_fingerprint(value: Tensor) -> str:
    tensor = value.detach().cpu().contiguous()
    array = tensor.numpy()
    digest = hashlib.sha256()
    digest.update(str(array.dtype).encode("ascii"))
    digest.update(_canonical_json(list(array.shape)))
    digest.update(array.tobytes(order="C"))
    return digest.hexdigest()


def _array_fingerprint(value: np.ndarray) -> str:
    array = np.ascontiguousarray(value)
    digest = hashlib.sha256()
    digest.update(str(array.dtype).encode("ascii"))
    digest.update(_canonical_json(list(array.shape)))
    digest.update(array.tobytes(order="C"))
    return digest.hexdigest()


def _task(value: str) -> str:
    result = str(value).strip().lower()
    if result not in H1_TRUST_TASKS:
        raise ValueError(f"task must be one of {H1_TRUST_TASKS}")
    return result


def _finite_positive(value: float) -> bool:
    return math.isfinite(float(value)) and float(value) > 0.0


@dataclass(frozen=True)
class H1TrustPlan:
    """Immutable stateless reference-stream plan for the H1 trust term."""

    grid_size: int
    horizon: float
    root_seed: int = H1_TRUST_PRODUCTION_ROOT_SEED
    label: int = 3
    banks_per_update: int = H1_TRUST_BANKS_PER_UPDATE
    states_per_bank: int = H1_TRUST_STATES_PER_BANK
    bin_counts: tuple[int, ...] = H1_TRUST_BIN_COUNTS
    schema: str = H1_TRUST_SCHEMA + "-plan"
    schema_version: int = H1_TRUST_SCHEMA_VERSION
    stream_version: str = H1_TRUST_STREAM_VERSION

    def __post_init__(self) -> None:
        if int(self.grid_size) <= 1:
            raise ValueError("grid_size must be greater than one")
        if not _finite_positive(float(self.horizon)):
            raise ValueError("horizon must be finite and positive")
        if int(self.root_seed) < 0:
            raise ValueError("root_seed must be nonnegative")
        if int(self.label) < 0:
            raise ValueError("label must be nonnegative")
        if int(self.banks_per_update) != H1_TRUST_BANKS_PER_UPDATE:
            raise ValueError("H1 trust v1 freezes two banks per update")
        if int(self.states_per_bank) != H1_TRUST_STATES_PER_BANK:
            raise ValueError("H1 trust v1 freezes 32 states per bank")
        if tuple(int(value) for value in self.bin_counts) != H1_TRUST_BIN_COUNTS:
            raise ValueError("H1 trust v1 freezes time strata 4,4,4,4,16")
        if sum(int(value) for value in self.bin_counts) != int(
            self.states_per_bank
        ):
            raise ValueError("bin_counts must sum to states_per_bank")

    @property
    def pixels(self) -> int:
        return int(self.grid_size) ** 2

    @property
    def fingerprint(self) -> str:
        return _canonical_fingerprint(_plan_payload(self))


def _plan_payload(plan: H1TrustPlan) -> dict[str, Any]:
    return {
        "schema": str(plan.schema),
        "schema_version": int(plan.schema_version),
        "stream_version": str(plan.stream_version),
        "operator_version": H1_TRUST_OPERATOR_VERSION,
        "root_seed": int(plan.root_seed),
        "grid_size": int(plan.grid_size),
        "pixels": int(plan.pixels),
        "horizon": float(plan.horizon),
        "label": int(plan.label),
        "banks_per_update": int(plan.banks_per_update),
        "states_per_bank": int(plan.states_per_bank),
        "bin_counts": [int(value) for value in plan.bin_counts],
        "candidate_fields_in_seed": [],
        "reference_law": "Dirichlet(1)",
    }


def build_h1_trust_plan(
    *,
    grid_size: int,
    horizon: float,
    root_seed: int = H1_TRUST_PRODUCTION_ROOT_SEED,
    label: int = 3,
) -> H1TrustPlan:
    return H1TrustPlan(
        grid_size=int(grid_size),
        horizon=float(horizon),
        root_seed=int(root_seed),
        label=int(label),
    )


