"""H1 function-step trust helpers for D0 density-ratio controls.

The balanced BCE remains the scientific population objective.  This module
only supplies a moving, stopped-EMA proximal term on the *increment* of the
raw logit.  In particular, it deliberately does not penalize the absolute
Dirichlet energy of the learned logit, which would move the Bayes optimum.

For ``d = ell_raw - stop_gradient(ell_ema)`` the normalized fixed-grid
components are

``V(d) = E_nu[d ** 2]`` and

``G(d) = E_nu[Gamma_h(d, d) / (2 N ** 2)]``
       ``= E_nu[mean_e theta_e r_e(d) ** 2]``.

The reference states are generated by a stateless ``Dirichlet(1)`` stream.
They are independent of candidate ordering and use the same frozen five-bin
time design for teacher and null tasks.  No sampler functionality belongs in
this module.
"""

