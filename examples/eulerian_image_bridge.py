def make_synthetic_house_image(grid_size: int = 28) -> FloatArray:
    """Return a simple ``grid_size x grid_size`` grayscale house image."""
    if grid_size <= 1:
        raise ValueError("grid_size must be at least 2")
    yy, xx = np.mgrid[0:grid_size, 0:grid_size]
    x = (xx + 0.5) / float(grid_size)
    y = (yy + 0.5) / float(grid_size)

    body = (0.23 <= x) & (x <= 0.77) & (0.45 <= y) & (y <= 0.86)
    roof = (0.16 <= x) & (x <= 0.84) & (0.20 <= y) & (y <= 0.52)
    roof &= y >= 0.20 + 0.70 * np.abs(x - 0.50)
    door = (0.45 <= x) & (x <= 0.56) & (0.65 <= y) & (y <= 0.86)
    left_window = (0.31 <= x) & (x <= 0.40) & (0.55 <= y) & (y <= 0.65)
    right_window = (0.61 <= x) & (x <= 0.70) & (0.55 <= y) & (y <= 0.65)
    chimney = (0.65 <= x) & (x <= 0.73) & (0.18 <= y) & (y <= 0.36)

    image = np.zeros((grid_size, grid_size), dtype=np.float64)
    image[body] = 0.70
    image[roof] = 1.00
    image[chimney] = 0.85
    image[door] = 0.18
    image[left_window | right_window] = 0.08
    return _periodic_gaussian_blur_numpy(image, sigma=0.55)


def make_synthetic_butterfly_image(grid_size: int = 28) -> FloatArray:
    """Return a simple ``grid_size x grid_size`` grayscale butterfly image."""
    if grid_size <= 1:
        raise ValueError("grid_size must be at least 2")
    yy, xx = np.mgrid[0:grid_size, 0:grid_size]
    x = (xx + 0.5) / float(grid_size)
    y = (yy + 0.5) / float(grid_size)

    def gaussian(cx: float, cy: float, sx: float, sy: float, amp: float) -> FloatArray:
        return amp * np.exp(-0.5 * (((x - cx) / sx) ** 2 + ((y - cy) / sy) ** 2))

    image = np.zeros((grid_size, grid_size), dtype=np.float64)
    image += gaussian(0.32, 0.38, 0.13, 0.16, 1.00)
    image += gaussian(0.68, 0.38, 0.13, 0.16, 1.00)
    image += gaussian(0.35, 0.67, 0.12, 0.14, 0.85)
    image += gaussian(0.65, 0.67, 0.12, 0.14, 0.85)
    image += gaussian(0.50, 0.53, 0.035, 0.22, 0.95)
    image += gaussian(0.45, 0.22, 0.025, 0.10, 0.35)
    image += gaussian(0.55, 0.22, 0.025, 0.10, 0.35)
    return np.clip(image, 0.0, None)


def normalize_image_to_measure(image: np.ndarray, *, floor: float = 1e-8) -> FloatArray:
    """Flatten a non-negative image into a positive probability vector."""
    arr = np.asarray(image, dtype=np.float64)
    if arr.ndim != 2:
        raise ValueError("image must have shape (H, W)")
    if np.any(~np.isfinite(arr)):
        raise ValueError("image contains non-finite values")
    arr = np.maximum(arr, 0.0) + float(floor)
    total = float(arr.sum())
    if total <= 0.0:
        raise ValueError("image has zero total mass")
    return (arr / total).reshape(-1)


def natural_horizon(config: EulerianImageBridgeConfig) -> float:
    """Return the full bridge time horizon for ``config``."""
    return float(config.horizon_scale) / (
        (2.0 * float(config.alpha) + 1.0) * float(config.grid_size * config.grid_size)
    )


def _periodic_gaussian_blur_numpy(image: np.ndarray, *, sigma: float) -> FloatArray:
    arr = np.asarray(image, dtype=np.float64)
    if sigma <= 0.0:
        return arr.copy()
    radius = max(1, int(math.ceil(3.0 * float(sigma))))
    offsets = np.arange(-radius, radius + 1, dtype=np.float64)
    kernel = np.exp(-0.5 * (offsets / float(sigma)) ** 2)
    kernel /= np.sum(kernel)

    out = np.zeros_like(arr, dtype=np.float64)
    for offset, weight in zip(range(-radius, radius + 1), kernel):
        out += float(weight) * np.roll(arr, shift=offset, axis=-1)
    arr = out
    out = np.zeros_like(arr, dtype=np.float64)
    for offset, weight in zip(range(-radius, radius + 1), kernel):
        out += float(weight) * np.roll(arr, shift=offset, axis=-2)
    return out


def terminal_potential_numpy(
    masses: np.ndarray,
    target_masses: np.ndarray,
    config: EulerianImageBridgeConfig,
) -> FloatArray:
    """Return the multi-scale blurred image discrepancy ``Phi_h(s)``."""
    n = int(config.grid_size)
    num_pixels = n * n
    states = np.asarray(masses, dtype=np.float64)
    target = np.asarray(target_masses, dtype=np.float64).reshape(num_pixels)
    if states.ndim == 1:
        states = states[None, :]
        squeeze = True
    elif states.ndim == 2:
        squeeze = False
    else:
        raise ValueError("masses must have shape (N,) or (B, N)")
    if states.shape[1] != num_pixels:
        raise ValueError("masses have the wrong number of pixels")

    density = states.reshape(-1, n, n) * float(num_pixels)
    target_density = target.reshape(n, n) * float(num_pixels)
    weights = np.asarray(config.blur_weights, dtype=np.float64)
    weights = weights / float(weights.sum())

    phi = np.zeros((states.shape[0],), dtype=np.float64)
    for sigma, weight in zip(config.blur_sigmas, weights):
        diff = density - target_density[None, :, :]
        if sigma > 0.0:
            diff = np.stack(
                [_periodic_gaussian_blur_numpy(frame, sigma=float(sigma)) for frame in diff],
                axis=0,
            )
        phi += float(weight) * np.mean(diff * diff, axis=(1, 2))
    return phi[0] if squeeze else phi


def terminal_preference_numpy(
    masses: np.ndarray,
    target_masses: np.ndarray,
    config: EulerianImageBridgeConfig,
) -> FloatArray:
    """Return ``epsilon + (1 - epsilon) exp(-lambda Phi_h(s))``."""
    phi = terminal_potential_numpy(masses, target_masses, config)
    return config.terminal_floor + (1.0 - config.terminal_floor) * np.exp(
        -float(config.terminal_lambda) * phi
    )


def _gaussian_kernel1d_torch(sigma: float, *, device: torch.device, dtype: torch.dtype) -> Tensor:
    radius = max(1, int(math.ceil(3.0 * float(sigma))))
    offsets = torch.arange(-radius, radius + 1, device=device, dtype=dtype)
    kernel = torch.exp(-0.5 * (offsets / float(sigma)) ** 2)
    return kernel / kernel.sum().clamp_min(torch.finfo(dtype).eps)


def _periodic_gaussian_blur_torch(images: Tensor, *, sigma: float) -> Tensor:
    if sigma <= 0.0:
        return images
    if images.ndim != 4:
        raise ValueError("images must have shape (B, C, H, W)")
    kernel = _gaussian_kernel1d_torch(sigma, device=images.device, dtype=images.dtype)
    radius = int((kernel.numel() - 1) // 2)
    channels = int(images.shape[1])

    kernel_x = kernel.view(1, 1, 1, -1).expand(channels, 1, 1, -1)
    out = F.pad(images, (radius, radius, 0, 0), mode="circular")
    out = F.conv2d(out, kernel_x, groups=channels)

    kernel_y = kernel.view(1, 1, -1, 1).expand(channels, 1, -1, 1)
    out = F.pad(out, (0, 0, radius, radius), mode="circular")
    return F.conv2d(out, kernel_y, groups=channels)


def _target_batch(target_masses: Tensor, batch_size: int) -> Tensor:
    if target_masses.ndim == 1:
        return target_masses[None, :].expand(batch_size, -1)
    if target_masses.ndim == 2 and target_masses.shape[0] == batch_size:
        return target_masses
    raise ValueError("target_masses must have shape (N,) or (B, N)")


def terminal_potential_torch(
    masses: Tensor,
    target_masses: Tensor,
    config: EulerianImageBridgeConfig,
) -> Tensor:
    """Differentiable PyTorch version of :func:`terminal_potential_numpy`."""
    if masses.ndim != 2:
        raise ValueError("masses must have shape (B, N)")
    n = int(config.grid_size)
    num_pixels = n * n
    if masses.shape[1] != num_pixels:
        raise ValueError("masses have the wrong number of pixels")
    target = _target_batch(target_masses.to(device=masses.device, dtype=masses.dtype), masses.shape[0])

    density = masses.reshape(-1, 1, n, n) * float(num_pixels)
    target_density = target.reshape(-1, 1, n, n) * float(num_pixels)
    diff = density - target_density

    weight_sum = float(sum(config.blur_weights))
    phi = torch.zeros((masses.shape[0],), device=masses.device, dtype=masses.dtype)
    for sigma, weight in zip(config.blur_sigmas, config.blur_weights):
        blurred = _periodic_gaussian_blur_torch(diff, sigma=float(sigma))
        phi = phi + float(weight / weight_sum) * torch.mean(blurred.square(), dim=(1, 2, 3))
    return phi


def terminal_preference_torch(
    masses: Tensor,
    target_masses: Tensor,
    config: EulerianImageBridgeConfig,
) -> Tensor:
    """Differentiable PyTorch version of :func:`terminal_preference_numpy`."""
    phi = terminal_potential_torch(masses, target_masses, config)
    return float(config.terminal_floor) + (1.0 - float(config.terminal_floor)) * torch.exp(
        -float(config.terminal_lambda) * phi
    )


class PositiveHeatPotentialCNN(nn.Module):
    """Positive CNN surrogate for ``v_tau(s)=E_s[g_h(S_tau)]``.

    The network output is bounded in ``[terminal_floor, 1]``.  The forward pass
    blends the learned value with the exact terminal score so that
    ``v_0(s) = g_h(s)`` holds exactly.
    """

    def __init__(
        self,
        config: EulerianImageBridgeConfig,
        *,
        hidden_channels: int = 48,
        hidden_dim: int = 128,
        terminal_blend_fraction: float = 0.05,
    ) -> None:
        super().__init__()
        if hidden_channels <= 0 or hidden_dim <= 0:
            raise ValueError("hidden sizes must be positive")
        if terminal_blend_fraction <= 0.0:
            raise ValueError("terminal_blend_fraction must be positive")
        self.config = config
        self.horizon = natural_horizon(config)
        self.terminal_blend_fraction = float(terminal_blend_fraction)
        channels = int(hidden_channels)
        self.conv = nn.Sequential(
            nn.Conv2d(4, channels, kernel_size=3, padding=1, padding_mode="circular"),
            nn.SiLU(),
            nn.Conv2d(channels, channels, kernel_size=3, padding=1, padding_mode="circular"),
            nn.SiLU(),
            nn.Conv2d(channels, channels, kernel_size=3, padding=1, padding_mode="circular"),
            nn.SiLU(),
            nn.Conv2d(channels, channels, kernel_size=3, padding=1, padding_mode="circular"),
            nn.SiLU(),
        )
        self.head = nn.Sequential(
            nn.Flatten(),
            nn.Linear(channels * config.grid_size * config.grid_size, int(hidden_dim)),
            nn.SiLU(),
            nn.Linear(int(hidden_dim), 1),
        )

    def terminal_score(self, masses: Tensor, target_masses: Tensor) -> Tensor:
        return terminal_preference_torch(masses, target_masses, self.config)

    def forward(self, tau: Tensor | float, masses: Tensor, target_masses: Tensor) -> Tensor:
        if masses.ndim != 2:
            raise ValueError("masses must have shape (B, N)")
        batch_size = int(masses.shape[0])
        tau_tensor = torch.as_tensor(tau, dtype=masses.dtype, device=masses.device)
        if tau_tensor.ndim == 0:
            tau_tensor = tau_tensor.repeat(batch_size)
        if tau_tensor.shape != (batch_size,):
            raise ValueError("tau must be scalar or have shape (B,)")
        target = _target_batch(target_masses.to(device=masses.device, dtype=masses.dtype), batch_size)

        n = int(self.config.grid_size)
        num_pixels = n * n
        density = masses.reshape(batch_size, 1, n, n) * float(num_pixels)
        target_density = target.reshape(batch_size, 1, n, n) * float(num_pixels)
        tau_channel = (tau_tensor / max(self.horizon, 1e-12)).view(batch_size, 1, 1, 1)
        tau_channel = tau_channel.expand(batch_size, 1, n, n)
        inputs = torch.cat([density, target_density, density - target_density, tau_channel], dim=1)

        learned = float(self.config.terminal_floor) + (
            1.0 - float(self.config.terminal_floor)
        ) * torch.sigmoid(self.head(self.conv(inputs))).squeeze(1)
        terminal = self.terminal_score(masses, target)
        tau0 = max(self.terminal_blend_fraction * self.horizon, 1e-12)
        blend = (1.0 - torch.exp(-tau_tensor / tau0)).clamp(0.0, 1.0)
        value = (1.0 - blend) * terminal + blend * learned
        return value.clamp_min(float(self.config.terminal_floor))


