def _edge_color_classes(grid_size: int) -> list[tuple[np.ndarray, np.ndarray]]:
    n = int(grid_size)
    classes: list[list[tuple[int, int]]] = [[], [], [], []]
    for y in range(n):
        for x in range(n):
            tail = y * n + x
            classes[x % 2].append((tail, y * n + ((x + 1) % n)))
            classes[2 + (y % 2)].append((tail, ((y + 1) % n) * n + x))
    result: list[tuple[np.ndarray, np.ndarray]] = []
    for edges in classes:
        tails = np.asarray([edge[0] for edge in edges], dtype=np.int64)
        heads = np.asarray([edge[1] for edge in edges], dtype=np.int64)
        result.append((tails, heads))
    return result


def _validate_state_batch(states: np.ndarray, config: EulerianImageBridgeConfig) -> tuple[FloatArray, bool]:
    arr = np.asarray(states, dtype=np.float64)
    n2 = int(config.grid_size * config.grid_size)
    if arr.ndim == 1:
        arr = arr[None, :]
        squeeze = True
    elif arr.ndim == 2:
        squeeze = False
    else:
        raise ValueError("states must have shape (N,) or (B, N)")
    if arr.shape[1] != n2:
        raise ValueError("state has the wrong number of pixels")
    if np.any(~np.isfinite(arr)):
        raise ValueError("state contains non-finite values")
    arr = np.maximum(arr, float(config.mass_floor))
    arr = arr / arr.sum(axis=1, keepdims=True)
    return arr, squeeze


def _edge_split_step_numpy(
    states: FloatArray,
    dt: float,
    config: EulerianImageBridgeConfig,
    rng: np.random.Generator,
    *,
    potential_value: FloatArray | None = None,
    potential_grad: FloatArray | None = None,
    deterministic: bool = False,
) -> tuple[FloatArray, int, int]:
    if dt < 0.0 or not math.isfinite(dt):
        raise ValueError("dt must be non-negative and finite")
    if dt == 0.0:
        return states.copy(), 0, 0
    n = int(config.grid_size)
    inv_h2 = float(n * n)
    alpha = float(config.alpha)
    tiny = float(config.value_floor)
    out = np.asarray(states, dtype=np.float64).copy()
    clipped = 0
    proposed = 0

    if potential_grad is not None:
        grad = np.asarray(potential_grad, dtype=np.float64)
        if grad.shape != out.shape:
            raise ValueError("potential_grad must have the same shape as states")
        value = np.asarray(potential_value, dtype=np.float64).reshape(-1, 1)
        if value.shape[0] != out.shape[0]:
            raise ValueError("potential_value must have shape (B,)")
        value = np.maximum(value, tiny)
    else:
        grad = None
        value = None

    sqrt_dt = math.sqrt(float(dt))
    for tails, heads in _edge_color_classes(n):
        a = out[:, tails]
        b = out[:, heads]
        denom = a + b
        safe = denom > tiny
        harmonic = np.zeros_like(denom)
        ratio = np.zeros_like(denom)
        harmonic[safe] = (a[safe] * b[safe]) / denom[safe]
        ratio[safe] = (a[safe] - b[safe]) / denom[safe]
        theta = ((2.0 * alpha + 1.0) / alpha) * harmonic
        rate = (2.0 * alpha + 1.0) * inv_h2 * ratio

        if grad is not None and value is not None:
            grad_delta = grad[:, heads] - grad[:, tails]
            rate = rate + 2.0 * theta * inv_h2 * grad_delta / value

        noise = 0.0
        if not deterministic:
            noise = np.sqrt(np.maximum(2.0 * theta * inv_h2, 0.0)) * sqrt_dt
            noise = noise * rng.standard_normal(size=theta.shape)
        d_flux = rate * float(dt) + noise

        pos_clip = d_flux > config.limiter_fraction * a
        neg_clip = d_flux < -config.limiter_fraction * b
        clipped += int(np.count_nonzero(pos_clip) + np.count_nonzero(neg_clip))
        proposed += int(d_flux.size)
        d_flux = np.minimum(d_flux, config.limiter_fraction * a)
        d_flux = np.maximum(d_flux, -config.limiter_fraction * b)

        out[:, tails] -= d_flux
        out[:, heads] += d_flux
        out = np.maximum(out, float(config.mass_floor))
        out /= out.sum(axis=1, keepdims=True)
    return out, clipped, proposed


def _steps_for_time(total_time: float, config: EulerianImageBridgeConfig, num_steps: int | None) -> int:
    if total_time <= 0.0:
        return 0
    if num_steps is not None:
        return max(1, int(num_steps))
    full_horizon = natural_horizon(config)
    return max(1, int(math.ceil(config.num_steps * float(total_time) / full_horizon)))


def simulate_free_rollout(
    initial_state: np.ndarray,
    total_time: float,
    config: EulerianImageBridgeConfig,
    *,
    rng: np.random.Generator | None = None,
    num_steps: int | None = None,
    return_trajectory: bool = False,
    deterministic: bool = False,
) -> EulerianRollout:
    """Simulate the free harmonic-mobility Eulerian image diffusion."""
    rng = np.random.default_rng() if rng is None else rng
    states, squeeze = _validate_state_batch(initial_state, config)
    total_time = float(total_time)
    if total_time < 0.0 or not math.isfinite(total_time):
        raise ValueError("total_time must be non-negative and finite")
    steps = _steps_for_time(total_time, config, num_steps)
    if steps == 0:
        times = np.asarray([0.0], dtype=np.float64)
        traj = states[None, 0 if squeeze else slice(None)].copy()
        final = states[0].copy() if squeeze else states.copy()
        return EulerianRollout(times=times, trajectory=traj, final_state=final, clipping_fraction=0.0)

    dt = total_time / float(steps)
    times = np.linspace(0.0, total_time, steps + 1, dtype=np.float64)
    traj = [states[0].copy() if squeeze else states.copy()] if return_trajectory else []
    clipped = 0
    proposed = 0
    for _ in range(steps):
        states, c_step, p_step = _edge_split_step_numpy(
            states,
            dt,
            config,
            rng,
            deterministic=deterministic,
        )
        clipped += c_step
        proposed += p_step
        if return_trajectory:
            traj.append(states[0].copy() if squeeze else states.copy())

    final = states[0].copy() if squeeze else states.copy()
    if return_trajectory:
        trajectory = np.asarray(traj, dtype=np.float64)
    else:
        trajectory = np.asarray([final], dtype=np.float64)
    return EulerianRollout(
        times=times if return_trajectory else np.asarray([total_time], dtype=np.float64),
        trajectory=trajectory,
        final_state=final,
        clipping_fraction=0.0 if proposed == 0 else float(clipped) / float(proposed),
    )


