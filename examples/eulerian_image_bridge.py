def sample_proposal_states(
    num_samples: int,
    house_masses: np.ndarray,
    target_masses: np.ndarray,
    config: EulerianImageBridgeConfig,
    *,
    rng: np.random.Generator | None = None,
    noise_weight: float = 0.05,
) -> FloatArray:
    """Sample states used to train the heat-potential surrogate."""
    if num_samples <= 0:
        raise ValueError("num_samples must be positive")
    rng = np.random.default_rng() if rng is None else rng
    house = np.asarray(house_masses, dtype=np.float64).reshape(-1)
    target = np.asarray(target_masses, dtype=np.float64).reshape(-1)
    if house.shape != target.shape:
        raise ValueError("house_masses and target_masses must have the same shape")

    states = np.empty((int(num_samples), house.shape[0]), dtype=np.float64)
    uniforms = rng.random(int(num_samples))
    mixes = rng.random(int(num_samples))
    for i, selector in enumerate(uniforms):
        if selector < 0.35:
            base = house
        elif selector < 0.70:
            r = mixes[i]
            base = (1.0 - r) * house + r * target
        elif selector < 0.85:
            base = target
        else:
            base = np.full_like(house, 1.0 / float(house.size))
        noise = rng.gamma(shape=1.0, scale=1.0, size=house.shape[0])
        noise = noise / noise.sum()
        states[i] = (1.0 - noise_weight) * base + noise_weight * noise
    states = np.maximum(states, float(config.mass_floor))
    return states / states.sum(axis=1, keepdims=True)


def make_feynman_kac_regression_batch(
    batch_size: int,
    house_masses: np.ndarray,
    target_masses: np.ndarray,
    config: EulerianImageBridgeConfig,
    *,
    rng: np.random.Generator | None = None,
    rollout_steps_per_sample: int = 16,
) -> RegressionBatch:
    """Build one supervised batch ``(tau, s, g_h(S_tau))``."""
    rng = np.random.default_rng() if rng is None else rng
    horizon = natural_horizon(config)
    tau = rng.uniform(0.0, horizon, size=int(batch_size)).astype(np.float64)
    states = sample_proposal_states(batch_size, house_masses, target_masses, config, rng=rng)
    targets = np.empty((int(batch_size),), dtype=np.float64)
    for i in range(int(batch_size)):
        rollout = simulate_free_rollout(
            states[i],
            float(tau[i]),
            config,
            rng=rng,
            num_steps=max(1, int(rollout_steps_per_sample)),
            return_trajectory=False,
        )
        targets[i] = float(terminal_preference_numpy(rollout.final_state, target_masses, config))
    return RegressionBatch(tau=tau, states=states, targets=targets)


def train_heat_potential_surrogate(
    model: PositiveHeatPotentialCNN,
    house_masses: np.ndarray,
    target_masses: np.ndarray,
    *,
    num_batches: int = 100,
    batch_size: int = 64,
    lr: float = 1e-3,
    rollout_steps_per_sample: int = 16,
    log_loss_weight: float = 0.05,
    rng: np.random.Generator | None = None,
    device: str | torch.device | None = None,
) -> dict[str, list[float]]:
    """Train ``model`` on the Feynman--Kac regression target."""
    if num_batches <= 0 or batch_size <= 0:
        raise ValueError("num_batches and batch_size must be positive")
    rng = np.random.default_rng() if rng is None else rng
    resolved_device = torch.device("cpu" if device is None else device)
    model.to(resolved_device)
    model.train()
    optimizer = torch.optim.Adam(model.parameters(), lr=float(lr))
    target_tensor = torch.tensor(target_masses, dtype=torch.float32, device=resolved_device)
    history: dict[str, list[float]] = {"loss": [], "mse": [], "log_mse": []}

    for _ in range(int(num_batches)):
        batch = make_feynman_kac_regression_batch(
            batch_size,
            house_masses,
            target_masses,
            model.config,
            rng=rng,
            rollout_steps_per_sample=rollout_steps_per_sample,
        )
        tau = torch.tensor(batch.tau, dtype=torch.float32, device=resolved_device)
        states = torch.tensor(batch.states, dtype=torch.float32, device=resolved_device)
        y = torch.tensor(batch.targets, dtype=torch.float32, device=resolved_device)
        pred = model(tau, states, target_tensor)
        mse = torch.mean((pred - y).square())
        log_mse = torch.mean((torch.log(pred) - torch.log(y.clamp_min(1e-12))).square())
        loss = mse + float(log_loss_weight) * log_mse

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

        history["loss"].append(float(loss.detach().cpu()))
        history["mse"].append(float(mse.detach().cpu()))
        history["log_mse"].append(float(log_mse.detach().cpu()))
    return history


def _potential_value_and_grad(
    model: PositiveHeatPotentialCNN,
    tau: float,
    state: FloatArray,
    target_masses: FloatArray,
    device: torch.device,
) -> tuple[FloatArray, FloatArray]:
    state_t = torch.tensor(state[None, :], dtype=torch.float32, device=device, requires_grad=True)
    target_t = torch.tensor(target_masses, dtype=torch.float32, device=device)
    tau_t = torch.tensor([float(tau)], dtype=torch.float32, device=device)
    value_t = model(tau_t, state_t, target_t)
    grad_t = torch.autograd.grad(value_t.sum(), state_t, create_graph=False)[0]
    value = value_t.detach().cpu().numpy().astype(np.float64)
    grad = grad_t.detach().cpu().numpy().astype(np.float64)
    return value, grad


def simulate_conditioned_image_bridge(
    model: PositiveHeatPotentialCNN,
    house_masses: np.ndarray,
    target_masses: np.ndarray,
    config: EulerianImageBridgeConfig | None = None,
    *,
    rng: np.random.Generator | None = None,
    num_steps: int | None = None,
    save_every: int = 1,
    deterministic: bool = False,
    device: str | torch.device | None = None,
) -> ConditionedBridgeResult:
    """Simulate the terminally conditioned house-to-butterfly image bridge."""
    cfg = model.config if config is None else config
    if cfg != model.config:
        raise ValueError("config must match model.config")
    if save_every <= 0:
        raise ValueError("save_every must be positive")
    rng = np.random.default_rng() if rng is None else rng
    resolved_device = torch.device("cpu" if device is None else device)
    model.to(resolved_device)
    model.eval()

    state, squeeze = _validate_state_batch(house_masses, cfg)
    if not squeeze:
        raise ValueError("simulate_conditioned_image_bridge expects one initial image")
    target = np.asarray(target_masses, dtype=np.float64).reshape(-1)
    horizon = natural_horizon(cfg)
    steps = int(cfg.num_steps if num_steps is None else num_steps)
    if steps <= 0:
        raise ValueError("num_steps must be positive")
    dt = horizon / float(steps)

    saved_times = [0.0]
    saved_states = [state[0].copy()]
    saved_scores = [float(terminal_preference_numpy(state[0], target, cfg))]
    clipped = 0
    proposed = 0
    with torch.enable_grad():
        for step in range(steps):
            t = float(step) * dt
            tau = max(horizon - t, 0.0)
            value, grad = _potential_value_and_grad(model, tau, state[0], target, resolved_device)
            state, c_step, p_step = _edge_split_step_numpy(
                state,
                dt,
                cfg,
                rng,
                potential_value=value,
                potential_grad=grad,
                deterministic=deterministic,
            )
            clipped += c_step
            proposed += p_step
            if (step + 1) % int(save_every) == 0 or step + 1 == steps:
                saved_times.append(float(step + 1) * dt)
                saved_states.append(state[0].copy())
                saved_scores.append(float(terminal_preference_numpy(state[0], target, cfg)))

    return ConditionedBridgeResult(
        times=np.asarray(saved_times, dtype=np.float64),
        trajectory=np.asarray(saved_states, dtype=np.float64),
        terminal_scores=np.asarray(saved_scores, dtype=np.float64),
        clipping_fraction=0.0 if proposed == 0 else float(clipped) / float(proposed),
    )
