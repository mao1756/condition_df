from __future__ import annotations

r"""Example 9: Eulerian image-mass bridge from a house to a butterfly.

This module is a runnable companion to the fixed-grid terminal-conditioning
recipe in the manuscript.  A grayscale image is represented by a point in the
``28 x 28`` probability simplex.  The target image enters through a positive
Gibbs terminal score ``g_h``.  The backward heat potential

    u_t^h(s) = E_s[g_h(S^h(T - t))]

is approximated by a positive convolutional surrogate trained from free
Eulerian rollouts.  A conditioned sample path is then generated by adding the
edge flux

    (2 / h) theta_e(s) partial_e^h u_t^h(s) / u_t^h(s)

to the conservative free edge flux.

The code is intentionally small and notebook-friendly.  It is meant as a
numerically stable experiment scaffold, not as a tuned image-generation system.
"""

